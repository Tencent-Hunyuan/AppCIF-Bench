# ====================================================================
# 工具函数: 从标准格式生成 background + question (用于模型测试)
# ====================================================================

def generate_background(case: dict) -> str:
    """
    从标准化案例生成 background 文本(发送给模型的卷宗原文)。

    生成格式:
    【一、卷宗背景与系统身份确认】
    1.案件编号：...
    2.卷宗唯一性：...
    【二、卷宗原文】
    卷宗编号：SP-XXX-XXX·标题
    背景约束：...（如有）
    身份名分确认：...（如有）
    裁断主体：主体名
    【起因】：...
    【经过行为描述】：...
    【结果】：...
    """
    parts = []
    dossiers = case['dossiers']

    # === 第一部分: 卷宗背景与系统身份确认 ===
    parts.append('【一、卷宗背景与系统身份确认】\n')

    dossier_ids = list(dossiers.keys())
    parts.append(f"1.案件编号：{'、'.join(dossier_ids)}\n")
    parts.append('2.卷宗唯一性：卷宗为唯一事实来源。严禁引入任何外部信息。\n')

    # === 第二部分: 卷宗原文 ===
    parts.append('\n【二、卷宗原文】\n')

    for did, dossier in dossiers.items():
        title = dossier.get('title', '')
        all_subjects = dossier['subjects']

        # 卷宗头部信息
        parts.append(f'\n卷宗编号：{did}·{title}\n')

        # 卷宗级背景约束
        background = dossier.get('background', '')
        if background:
            parts.append(f'背景约束：{background}。\n')

        # 卷宗级身份信息
        identities = dossier.get('identities', {})
        if identities:
            parts.append('身份名分确认：')
            identity_strs = [f'{person}（{role}）' for person, role in identities.items()]
            parts.append('、'.join(identity_strs))
            parts.append('。\n')

        parts.append(f"裁断主体：{'、'.join(all_subjects)}\n")

        if 'sub_pages' in dossier:
            dossier_cause = dossier.get('起因', '')
            if dossier_cause:
                parts.append(f'\n【起因】：{dossier_cause}\n')

            parts.append('\n【经过行为描述】：\n')
            for page_id, page in dossier['sub_pages'].items():
                page_title = page.get('page_title', '')
                page_subjects = page.get('subjects', [])
                parts.append(f'\n子页 {page_id}：')
                if page_title:
                    parts.append(page_title)
                parts.append('\n')

                page_cause = page.get('起因', '')
                if page_cause:
                    parts.append(f'【起因】：{page_cause}\n')

                for subj in page_subjects:
                    if subj in page:
                        parts.append(f'{page[subj]}\n')

                page_result = page.get('结果', '')
                if page_result:
                    parts.append(f'【结果】：{page_result}\n')

                supplement = page.get('行为描述补充', '')
                if supplement:
                    parts.append(f'\n【行为描述补充】：{supplement}\n')

            dossier_result = dossier.get('结果', '')
            if dossier_result:
                parts.append(f'\n【结果】：{dossier_result}\n')

        else:
            cause = dossier.get('起因', '')
            if cause:
                parts.append(f'\n【起因】：{cause}\n')

            parts.append('\n【经过行为描述】：\n')
            for subj in all_subjects:
                if subj in dossier:
                    parts.append(f'{dossier[subj]}\n')

            supplement = dossier.get('行为描述补充', '')
            if supplement:
                parts.append(f'\n【行为描述补充】：{supplement}\n')

            result = dossier.get('结果', '')
            if result:
                parts.append(f'\n【结果】：{result}\n')

    return ''.join(parts)


def generate_question(case: dict) -> str:
    """
    从标准化案例生成 question 文本(裁断指令)。

    根据 system_prompt.md 第十二章，合法启动句式:
    - "请裁断卷宗"
    - "审理如下卷宗"
    - "依春秋断狱算法进行裁断"
    - "对卷宗进行审理"
    """
    judgments = case['judgments']

    if len(judgments) == 1:
        task = judgments[0]
        return f"请裁断卷宗，裁断本卷宗中的{task['subject']}。"

    task_parts = []
    for task in judgments:
        did = task['dossier_id']
        subj = task['subject']
        task_parts.append(f"对卷宗{did}中的{subj}进行裁断")

    return f"请裁断卷宗，{'，'.join(task_parts)}。"


def convert_to_legacy_format(case: dict) -> dict:
    """
    将标准格式转换为旧版 test_cases.py 的 background+question 格式。
    用于兼容已有的测试流程。
    """
    return {
        'background': generate_background(case),
        'question': generate_question(case),
        'rubrics': case.get('rubrics', ''),
    }


def get_subject_text(dossier: dict, subject: str) -> str:
    """
    从卷宗数据中提取指定主体的完整行为描述文本。

    规则:
    - 简单卷宗: 直接取 dossier[subject]
    - 子页卷宗: 合并所有包含该主体的子页中的行为描述 + 行为描述补充
    """
    if 'sub_pages' not in dossier:
        text = dossier.get(subject, '')
        supplement = dossier.get('行为描述补充', '')
        return f"{text}\n{supplement}" if supplement else text

    texts = []
    for _page_id, page in dossier['sub_pages'].items():
        if subject in page:
            texts.append(page[subject])
        supplement = page.get('行为描述补充', '')
        if supplement and subject in page.get('subjects', []):
            texts.append(supplement)
    return '\n'.join(texts)


def get_full_dossier_text(dossier: dict) -> str:
    """
    获取卷宗的完整文本(含起因/所有行为描述/结果)。

    用途:
    - E模块启动判定(是否存在伦理对象关键词)
    - 现代法律模块全文扫描
    - Q模块反向表述跨子页穿透检查
    """
    if 'sub_pages' not in dossier:
        parts = []
        if '起因' in dossier:
            parts.append(dossier['起因'])
        for subj in dossier['subjects']:
            if subj in dossier:
                parts.append(dossier[subj])
        if '行为描述补充' in dossier:
            parts.append(dossier['行为描述补充'])
        if '结果' in dossier:
            parts.append(dossier['结果'])
        return '\n'.join(parts)

    parts = []
    if '起因' in dossier:
        parts.append(dossier['起因'])
    for _page_id, page in dossier['sub_pages'].items():
        if '起因' in page:
            parts.append(page['起因'])
        for subj in page.get('subjects', []):
            if subj in page:
                parts.append(page[subj])
        if '行为描述补充' in page:
            parts.append(page['行为描述补充'])
        if '结果' in page:
            parts.append(page['结果'])
    if '结果' in dossier:
        parts.append(dossier['结果'])
    return '\n'.join(parts)


